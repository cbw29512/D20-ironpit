"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
global.window = globalThis;
const load = name => vm.runInThisContext(fs.readFileSync(path.join(__dirname, name), "utf8"), {filename:name});
window.IRON_PIT_DICE = { rolls:[2,2], roll(sides){ return this.rolls.shift(); }, rollMany(count,sides){ return Array.from({length:count},()=>this.roll(sides)); } };
window.IRON_PIT_BROWSER_DAMAGE_DEFENSE_RULES = { resolveDamage:(state,total,type)=>({applied:total}) };
window.IRON_PIT_BROWSER_ATTACK = { applyDamage(state,total){ state.current_hp -= total; } };
load("browser-grapple.js");
load("browser-start-of-turn-timed-burn.js");
const make = (id, side, position) => ({ combatant_id:id, side, position_ft:position, state:{ template:{name:id,max_hp:20,damage_immunities:[]}, current_hp:20, is_alive:true,is_dead:false,is_unconscious:false,active_effect_ids:[],grapple_sources:[],timed_effects:[] } });
const rug=make("rug","monsters",0), victim=make("victim","heroes",5), setup={heroes:[victim],monsters:[rug]};
const periodic={source_name:"Smother",dice_count:2,dice_size:6,damage_bonus:3,damage_type:"bludgeoning"};
assert.deepEqual(window.IRON_PIT_BROWSER_GRAPPLE.apply(victim.state,"rug",13,5,true,false,periodic,{blinds:true,preventsBreathing:true}), ["grappled","restrained"]);
assert(victim.state.active_effect_ids.includes("blinded"));
assert(victim.state.grapple_sources[0].prevents_breathing);
const result=window.IRON_PIT_BROWSER_START_OF_TURN_TIMED_BURN.resolve(1,1,victim,setup);
assert.equal(victim.state.current_hp,13);
assert.match(result.events[0].description,/Smother deals 7 bludgeoning/);
window.IRON_PIT_BROWSER_GRAPPLE.release(victim.state,"rug");
assert(!victim.state.active_effect_ids.includes("blinded"));
assert.equal(victim.state.breath_hold_rounds_remaining,null);
console.log("2014 Rug Smother browser regressions passed.");
