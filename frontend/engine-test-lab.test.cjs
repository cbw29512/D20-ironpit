"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = __dirname;
const page = fs.readFileSync(path.join(root, "engine-test-lab.html"), "utf8");
const js = fs.readFileSync(path.join(root, "engine-test-lab.js"), "utf8");
const scripts = [...page.matchAll(/<script defer src="([^"]+)"/g)].map(row => row[1]);
assert.ok(page.includes('id="fight"') && page.includes('id="results"'));
assert.ok(page.includes("engine-test-lab.js"));
assert.ok(scripts.indexOf("browser-engine.js") >= 0);
assert.ok(scripts.indexOf("browser-engine.js") < scripts.indexOf("engine-test-lab.js"));
for (const script of scripts) assert.ok(fs.existsSync(path.join(root, script)), "Missing runtime file: " + script);
assert.ok(js.includes("IRON_PIT_BROWSER_ENGINE.runEncounter") || js.includes("IRON_PIT_BROWSER_TURBO.runSeeded"));
assert.ok(js.includes("applied_condition_ids") && js.includes("damage_components"), "Report must include observed conditions and typed damage components.");
assert.ok(js.includes("observed events only; not RAW correctness"), "Observed mechanics must not be mislabeled as certified correctness.");
assert.ok(!js.includes("resolveAttack("), "Test Lab must not implement a new combat resolver.");
assert.ok(js.includes("cards_unchanged") && js.includes("cardSnapshot"), "Every fight must check for certified card mutation.");
assert.ok(js.includes("seed + count - 1 > 0xffffffff"), "Batch seed must fit the existing Turbo 32-bit seed contract.");
assert.ok(page.includes('id="hero-cards"') && page.includes('id="monster-cards"'), "Both clickable galleries are required.");
assert.ok(page.includes('id="quick-fight"'), "One-click fight action must be present.");
assert.ok(js.includes('execute([{selection:selection(),seed:') && js.includes("paintCards"), "Card selection must use the existing engine lab runner.");
console.log("Engine Test Lab static integration checks passed.");
